import { API_ERROR_CODES, API_VERSION, operations } from './api.ts';
import { errorBody, events, health, outputs } from './api-fixtures.ts';

/** Where the exported contract lives: `packages/devlink/api/`. */
export const API_CONTRACT_DIR = new URL('../../api/', import.meta.url);

/**
 * The API contract as files for other languages (ADR 0013): `schema.json` describes the operations,
 * error codes and event types; `fixtures.json` holds a sample of everything the daemon sends.
 */
export function apiDocuments(): Record<string, string> {
  const schema = {
    $comment: 'Generated by `npm run api:export` from src/daemon/api.ts. Do not edit.',
    apiVersion: API_VERSION,
    operations: Object.fromEntries(
      Object.entries(operations).map(([name, input]) => [
        name,
        { method: 'POST', path: `/v1/${name}`, input: input.json },
      ]),
    ),
    errorCodes: API_ERROR_CODES,
    eventTypes: events.map((event) => event.type),
  };
  const fixtures = {
    $comment: 'Generated by `npm run api:export` from src/daemon/api-fixtures.ts. Do not edit.',
    health,
    outputs,
    events,
    errorBody,
  };
  return { 'schema.json': stringify(schema), 'fixtures.json': stringify(fixtures) };
}

function stringify(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}
