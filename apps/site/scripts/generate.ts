// Writes the docs pages that come from elsewhere in the repository, so they cannot drift from it
// (ADR 0011): the CLI reference from the CLI's own help text, and the design records as they are.
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { USAGE } from '../../../packages/devlink/src/cli/main.ts';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..', '..');
const docs = join(site, 'src', 'content', 'docs');
const GITHUB = 'https://github.com/mikheil-gigauri/devlink/blob/main';
const NOTICE = '{/* Generated by apps/site/scripts/generate.ts. Edit the source, not this file. */}';

interface Entry {
  readonly syntax: string;
  readonly description: string;
  readonly options: string[];
}

/** The help text's sections: a title line, then commands, each followed by its indented options. */
function parseUsage(usage: string) {
  const sections: { title: string; entries: Entry[] }[] = [];
  const notes: string[] = [];
  for (const line of usage.split('\n')) {
    if (line.trim() === '' || line.startsWith('Usage:')) continue;
    if (!line.startsWith(' ')) {
      if (/^[A-Z][a-z ]+$/.test(line)) sections.push({ title: line, entries: [] });
      else notes.push(line);
      continue;
    }
    const section = sections.at(-1);
    if (!section) throw new Error(`Help text line outside a section: ${line}`);
    const [syntax = '', description = ''] = line.trim().split(/\s{2,}(?=[A-Z(])/);
    if (line.startsWith('      ')) section.entries.at(-1)?.options.push(line.trim());
    else section.entries.push({ syntax, description, options: [] });
  }
  return { sections, notes };
}

function cliReference(): string {
  const { sections, notes } = parseUsage(USAGE);
  const out = [
    '---',
    'title: CLI reference',
    'description: Every devlink command and option, from the CLI’s own help text.',
    '---',
    '',
    NOTICE,
    '',
    `This page is the output of \`devlink --help\`, laid out. ${notes.join(' ')}`,
    '',
  ];
  for (const { title, entries } of sections) {
    out.push(`## ${title}`, '');
    for (const { syntax, description, options } of entries) {
      out.push(`### \`devlink ${syntax}\``, '');
      if (description) out.push(`${description}.`, '');
      for (const option of options) {
        const [flags = '', text] = option.split(/\s{2,}(?=[A-Z(])/);
        out.push(
          text
            ? `- \`${flags}\`: ${text}.`
            : `- ${flags
                .split(/\s{2,}/)
                .map((flag) => `\`${flag}\``)
                .join(', ')}`,
        );
      }
      if (options.length > 0) out.push('');
    }
  }
  return out.join('\n');
}

/** Links between records become links between pages; links elsewhere in the repository go to GitHub. */
function rewriteLinks(markdown: string, fromIndex: boolean): string {
  return markdown.replace(/\]\(([^)#\s]+)\.md(#[^)]*)?\)/g, (_match, target: string, hash = '') => {
    if (/^\d{4}-/.test(target)) return `](${fromIndex ? './' : '../'}${target}/${hash})`;
    return `](${GITHUB}/docs/adr/${target}.md${hash})`;
  });
}

async function designRecords(): Promise<void> {
  const source = join(repo, 'docs', 'adr');
  const target = join(docs, 'design');
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });

  const index = await readFile(join(source, 'README.md'), 'utf8');
  await writeFile(
    join(target, 'index.mdx'),
    [
      '---',
      'title: Design decisions',
      'description: Why devlink works the way it does, one decision at a time.',
      'sidebar:',
      '  order: 0',
      '  label: Overview',
      '---',
      '',
      NOTICE,
      '',
      rewriteLinks(index.replace(/^# .*\n+/, ''), true),
    ].join('\n'),
  );

  for (const file of (await readdir(source)).filter((name) => /^\d{4}-.*\.md$/.test(name))) {
    const text = await readFile(join(source, file), 'utf8');
    const heading = /^# (.+)$/m.exec(text)?.[1];
    if (!heading) throw new Error(`${file} has no title heading`);
    const number = Number(file.slice(0, 4));
    await writeFile(
      join(target, file.replace(/\.md$/, '.mdx')),
      [
        '---',
        `title: ${JSON.stringify(heading)}`,
        'sidebar:',
        `  order: ${number}`,
        '---',
        '',
        NOTICE,
        '',
        rewriteLinks(text.replace(/^# .*\n+/, ''), false),
      ].join('\n'),
    );
  }
}

/** The menu bar app's own snapshot images, so the site shows the menu as the tests last saw it. */
async function menuScreenshots(): Promise<void> {
  const source = join(repo, 'apps', 'menubar', 'Tests', 'DevlinkMenuTests', '__Snapshots__');
  const target = join(site, 'public', 'menu');
  await mkdir(target, { recursive: true });
  for (const name of ['online', 'window-library'].flatMap((shot) => [
    `${shot}.light.png`,
    `${shot}.dark.png`,
  ]))
    await copyFile(join(source, name), join(target, name));
}

await mkdir(join(docs, 'reference'), { recursive: true });
await writeFile(join(docs, 'reference', 'cli.mdx'), `${cliReference()}\n`);
await designRecords();
await menuScreenshots();
process.stdout.write('Generated the CLI reference, the design records and the menu screenshots.\n');
